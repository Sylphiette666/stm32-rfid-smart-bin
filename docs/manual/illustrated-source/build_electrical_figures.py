items=[]
paras=[x.split('\t',2)[-1] for x in (ROOT/'original_paragraphs.txt').read_text(encoding='utf-8').splitlines()]
def anchor(fragment):
    hits=[x for x in paras if fragment in x and x.startswith('步骤 ')]
    assert len(hits)==1,(fragment,hits)
    return hits[0]
def finish(d,name,fragment,caption,alt):
    d.save(name)
    items.append(dict(id=name,file='figures/'+name+'.png',anchor=anchor(fragment),position='before',caption=caption,alt=alt))
def txt(d,x,y,s,size=32,color=INK,bold=False):d.text((x,y),s,size,color,bold)
def note(d,s):txt(d,40,d.h-58,s,32,MUTED)
def box(d,x0,y0,x1,y1,title,fill='#F4F7F9'):
    d.rect((x0,y0,x1,y1),fill,INK,3,10);txt(d,x0+20,y0+15,title,36,INK,True)
def dot(d,x,y,color=INK):d.circle((x,y),7,color)
def terminal(d,x,y,label,side='left',color=INK):
    d.circle((x,y),7,'white',color,3)
    if side=='left':txt(d,x+17,y-62 if label in ('C','E','3 / D','2 / S') else y-23,label,32,color)
    else:txt(d,x-17,y-23,label,32,color); # use explicit text when right aligned needed
def gnd(d,x,y,label='GND'):
    d.line([(x,y),(x,y+15)],INK,3)
    for w,dy in [(24,15),(16,23),(8,31)]:d.line([(x-w,y+dy),(x+w,y+dy)],INK,3)
    if label:txt(d,x+35,y+3,label,32,MUTED)
def rh(d,x0,x1,y,label,color=INK):
    cx=(x0+x1)/2; hw=44
    d.line([(x0,y),(cx-hw,y)],color,4);d.rect((cx-hw,y-15,cx+hw,y+15),'white',color,3);d.line([(cx+hw,y),(x1,y)],color,4)
    txt(d,cx-50,y-62,label,32,color)
def rv(d,x,y0,y1,label,color=INK,side='right'):
    cy=(y0+y1)/2
    d.line([(x,y0),(x,cy-36)],color,4);d.rect((x-15,cy-36,x+15,cy+36),'white',color,3);d.line([(x,cy+36),(x,y1)],color,4)
    txt(d,x+28 if side=='right' else x-150,cy-25,label,32,color)
def cross(d,x,y,r=13):
    d.line([(x-r,y-r),(x+r,y+r)],RED,5);d.line([(x-r,y+r),(x+r,y-r)],RED,5)
def sw(d,x,y,label,closed=False):
    d.circle((x,y),6,'white',INK,3);d.circle((x+80,y),6,'white',INK,3)
    d.line([(x,y),(x+70,y if closed else y-35)],INK,4)
    txt(d,x+1,y-84,label,32,INK,True)

