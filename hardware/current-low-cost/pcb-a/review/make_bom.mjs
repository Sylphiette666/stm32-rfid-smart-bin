import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {Workbook} from '@oai/artifact-tool';
const here=path.dirname(fileURLToPath(import.meta.url));
const root=path.dirname(here);
const design=JSON.parse(await fs.readFile(path.join(root,'circuit.json'),'utf8'));
const header=['Designator','Quantity','Value','DNP','Assembly','ItemType','Footprint','MPN','Manufacturer','Supplier','Supplier_PN','Procure_if_missing','Original_ref','Notes'];
const natural=(a,b)=>a.ref.localeCompare(b.ref,'en',{numeric:true});
const conditional=new Set(['R8','R9','R10','R11','R12','R13','R14','R27','R28','R29','R33','R34','R35','R36','R37']);
const rows=design.parts.toSorted(natural).map(p=>{
 const hole=p.kind==='mounting_hole';
 let assembly=hole?'机械孔，无电子元件':p.dnp?'条件位，默认不装':conditional.has(p.ref)?'默认安装，可按条件变更':'默认安装';
 let notes=p.notes||'';
 if(p.kind==='jumper'){assembly='焊排针；跳帽另按配置';notes+=' 排针应焊接；DNP不表示跳帽状态。JP3—JP8默认不加帽，JP9加帽，JP10不加帽。';}
 if(/^J[1-6]$/.test(p.ref)) notes+=' 板孔距5.08mm、钻孔1.3mm；Phoenix库几何包络约11.22×11.125mm。已有KF301必须另核外壳、脚形、进线朝向，不能仅凭名称认定兼容。';
 if(['C1','C2','C3'].includes(p.ref)) notes+=' 安装包络D12.5mm、P5.00mm；1正2负；已有件小于包络可整形，超出需重新确认。';
 if(p.ref==='U1') notes+=' 本行只计1颗芯片。先焊下列U1_SOCKET插座，再插本芯片，不能把座与芯片作为两颗AHCT。';
 if(p.kind==='resistor') notes+=' 复用1/4W轴向件；R1/R2/R25/R26采用1%，其余按原清单。';
 if(p.kind==='capacitor') notes+=' 复用100nF瓷片，耐压至少16V，核5mm脚距及本体尺寸。';
 if(hole) notes='3.2mm非金属化安装孔，不采购孔件；M3绝缘立柱、螺钉和垫圈另按结构备齐。';
 const mpn=p.ref==='U1'?'SN74AHCT125N':p.kind==='npn'?'2N3904':'';
 const mfr=p.ref==='U1'?'Texas Instruments（核实物）':p.kind==='npn'?'脚序依据onsemi；已有品牌待核':'';
 return [p.ref,1,p.value,(p.dnp||hole)?'YES':'NO',assembly,hole?'mechanical':'pcb',p.footprint,mpn,mfr,'复用已购器件','',hole?0:1,p.original_ref||'',notes];
});
rows.push(['U1_SOCKET',1,'DIP14插座 7.62mm','NO','先焊插座，再插U1','accessory','与U1共用14孔；本项不是独立PCB位号','','','复用已购插座','',1,'','采购补充项：只需1只DIP14座，行距7.62mm、针距2.54mm。U1芯片另在U1行计1颗。不要生成第二个芯片贴装位。']);
const wb=Workbook.create();
const sh=wb.worksheets.add('BOM');
sh.getRange(`A1:N${rows.length+1}`).values=[header,...rows];
sh.showGridLines=false;
sh.freezePanes.freezeRows(1);
sh.getRange(`A1:N${rows.length+1}`).format.font={name:'Microsoft YaHei',size:10};
sh.getRange('A1:N1').format={fill:'#253F55',font:{name:'Microsoft YaHei',size:10,bold:true,color:'#FFFFFF'}};
sh.getRange(`A1:N${rows.length+1}`).format.rowHeight=24;
sh.getRange('A:A').format.columnWidth=16;
sh.getRange('B:B').format.columnWidth=10;
sh.getRange('C:C').format.columnWidth=27;
sh.getRange('D:D').format.columnWidth=10;
sh.getRange('E:E').format.columnWidth=36;
sh.getRange('F:F').format.columnWidth=16;
sh.getRange('G:N').format.columnWidth=38;
wb.recalculate();
const data=sh.getRange(`A1:N${rows.length+1}`).values;
if(data.length!==96) throw Error('Expected 94 PCB refs plus one socket accessory');
const quoted=v=>'"'+String(v??'').replaceAll('"','""')+'"';
await fs.writeFile(path.join(root,'manufacturing','bom.csv'),'\uFEFF'+data.map(r=>r.map(quoted).join(',')).join('\r\n')+'\r\n','utf8');
const inspect=await wb.inspect({kind:'table',range:'BOM!A1:F10',include:'values',tableMaxRows:10,tableMaxCols:6,maxChars:2500});
await fs.writeFile(path.join(here,'bom-inspection.ndjson'),inspect.ndjson,'utf8');
const png=await wb.render({sheetName:'BOM',range:'A1:F14',scale:1,format:'png'});
await fs.writeFile(path.join(here,'bom-preview.png'),new Uint8Array(await png.arrayBuffer()));
const summary={pcb_refs:design.parts.length,accessory_rows:1,csv_rows:rows.length,default_dnp:rows.filter(r=>r[3]==='YES').map(r=>r[0]),note:'Hand-solder existing-parts BOM. Generic supplier/MPNs unverified and intentionally blank; not a PCBA sourcing BOM.'};
await fs.writeFile(path.join(here,'bom-build-summary.json'),JSON.stringify(summary,null,2));
console.log(JSON.stringify(summary));
